import type { RepoAnalysis, EntityDefinition } from '../types';

export function generateReactCode(analysis: RepoAnalysis, activeEntity: EntityDefinition): string {
  const entityName = activeEntity.singular;
  const pluralName = activeEntity.plural;
  const fields = activeEntity.fields;

  const interfaceFields = fields
    .map((f) => {
      let tsType = 'string';
      if (f.type === 'number') tsType = 'number';
      if (f.type === 'boolean') tsType = 'boolean';
      if (f.type === 'array') tsType = 'string[]';
      return `  ${f.name}${f.required ? '' : '?'}: ${tsType};`;
    })
    .join('\n');

  const initialValues = fields
    .filter((f) => !f.isId)
    .map((f) => {
      let defaultVal = "''";
      if (f.type === 'number') defaultVal = '0';
      if (f.type === 'boolean') defaultVal = 'true';
      if (f.type === 'badge' && f.options?.length) defaultVal = `'${f.options[0]}'`;
      return `  ${f.name}: ${defaultVal},`;
    })
    .join('\n');

  return `/**
 * Generated by RepoCraft Frontend Studio
 * Target Backend: ${analysis.metadata.fullName} (${analysis.framework})
 * Entity: ${activeEntity.name}
 *
 * To run: Copy into your React + Tailwind application.
 */

import React, { useState, useMemo } from 'react';
import { Search, Plus, Filter, Download, Trash2, Edit2, ArrowUpDown } from 'lucide-react';

export interface ${entityName} {
${interfaceFields}
}

const INITIAL_DATA: ${entityName}[] = ${JSON.stringify(activeEntity.sampleData, null, 2)};

export default function ${entityName}Dashboard() {
  const [items, setItems] = useState<${entityName}[]>(INITIAL_DATA);
  const [searchQuery, setSearchQuery] = useState('');
  const [statusFilter, setStatusFilter] = useState('ALL');
  const [isModalOpen, setIsModalOpen] = useState(false);
  const [editingItem, setEditingItem] = useState<${entityName} | null>(null);

  // Form state
  const [formData, setFormData] = useState({
${initialValues}
  });

  // Filtered & searched data
  const filteredItems = useMemo(() => {
    return items.filter((item: any) => {
      const matchesSearch = Object.values(item).some((val) =>
        String(val).toLowerCase().includes(searchQuery.toLowerCase())
      );
      const matchesStatus =
        statusFilter === 'ALL' || !('status' in item) || item.status === statusFilter;
      return matchesSearch && matchesStatus;
    });
  }, [items, searchQuery, statusFilter]);

  const handleCreateOrUpdate = (e: React.FormEvent) => {
    e.preventDefault();
    if (editingItem) {
      setItems((prev) =>
        prev.map((it: any) => (it.id === (editingItem as any).id ? { ...it, ...formData } : it))
      );
    } else {
      const newItem: any = {
        id: 'id_' + Math.random().toString(36).substring(2, 9),
        ...formData,
      };
      setItems((prev) => [newItem, ...prev]);
    }
    setIsModalOpen(false);
    setEditingItem(null);
  };

  const handleDelete = (id: string) => {
    if (window.confirm('Are you sure you want to delete this record?')) {
      setItems((prev) => prev.filter((it: any) => it.id !== id));
    }
  };

  return (
    <div className="min-h-screen bg-slate-950 text-slate-100 p-6 lg:p-10 font-sans">
      <div className="max-w-7xl mx-auto space-y-8">
        {/* Header Zone */}
        <header className="flex flex-col md:flex-row md:items-center justify-between gap-4 pb-6 border-b border-slate-800">
          <div>
            <div className="flex items-center gap-2 text-xs text-slate-400 mb-1">
              <span>${analysis.metadata.fullName}</span>
              <span aria-hidden="true">·</span>
              <span>${analysis.framework}</span>
              <span aria-hidden="true">·</span>
              <span className="tabular-nums font-mono">{items.length} records</span>
            </div>
            <h1 className="text-2xl font-bold tracking-tight text-white">
              ${activeEntity.name}
            </h1>
          </div>

          <div className="flex items-center gap-3">
            <button
              onClick={() => {
                setEditingItem(null);
                setIsModalOpen(true);
              }}
              className="inline-flex items-center gap-2 px-4 py-2 text-sm font-medium text-white bg-indigo-600 hover:bg-indigo-500 rounded-lg transition-colors shadow-sm"
            >
              <Plus className="w-4 h-4" />
              <span>New ${entityName}</span>
            </button>
          </div>
        </header>

        {/* Toolbar Zone */}
        <div className="flex flex-col sm:flex-row items-center justify-between gap-4">
          <div className="relative w-full sm:w-80">
            <Search className="w-4 h-4 absolute left-3 top-1/2 -translate-y-1/2 text-slate-400" />
            <input
              type="text"
              placeholder="Search ${pluralName.toLowerCase()}..."
              value={searchQuery}
              onChange={(e) => setSearchQuery(e.target.value)}
              className="w-full pl-9 pr-4 py-2 text-sm bg-slate-900 border border-slate-800 rounded-lg text-slate-100 placeholder-slate-500 focus:outline-none focus:ring-2 focus:ring-indigo-500"
            />
          </div>

          {/* Interactive filter tabs */}
          <div className="flex items-center gap-1 p-1 bg-slate-900 border border-slate-800 rounded-lg self-stretch sm:self-auto">
            {['ALL', 'Active', 'Pending', 'Draft'].map((tab) => (
              <button
                key={tab}
                onClick={() => setStatusFilter(tab)}
                className={\`px-3 py-1 text-xs font-medium rounded transition-colors \${
                  statusFilter === tab
                    ? 'bg-indigo-600 text-white'
                    : 'text-slate-400 hover:text-slate-200'
                }\`}
              >
                {tab}
              </button>
            ))}
          </div>
        </div>

        {/* High-density Data Table */}
        <div className="border border-slate-800 rounded-xl bg-slate-900/60 overflow-hidden shadow-sm">
          <div className="overflow-x-auto">
            <table className="w-full text-left text-sm">
              <thead className="bg-slate-900/90 text-xs font-semibold text-slate-400 border-b border-slate-800">
                <tr>
${fields
  .map(
    (f) => `                  <th className="px-5 py-3.5 whitespace-nowrap">${f.label}</th>`
  )
  .join('\n')}
                  <th className="px-5 py-3.5 text-right whitespace-nowrap">Actions</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-800">
                {filteredItems.length === 0 ? (
                  <tr>
                    <td
                      colSpan={${fields.length + 1}}
                      className="px-6 py-12 text-center text-slate-500"
                    >
                      No ${pluralName.toLowerCase()} found matching your criteria.
                    </td>
                  </tr>
                ) : (
                  filteredItems.map((item: any) => (
                    <tr
                      key={item.id}
                      className="hover:bg-slate-800/40 transition-colors"
                    >
${fields
  .map((f) => {
    if (f.isId) {
      return `                      <td className="px-5 py-3.5 font-mono text-xs text-slate-400 tabular-nums">{item.${f.name}}</td>`;
    }
    if (f.type === 'number') {
      return `                      <td className="px-5 py-3.5 font-mono text-slate-200 tabular-nums">{item.${f.name}}</td>`;
    }
    if (f.type === 'badge') {
      return `                      <td className="px-5 py-3.5">
                        <span className="inline-block text-xs font-medium text-indigo-400">
                          {item.${f.name}}
                        </span>
                      </td>`;
    }
    return `                      <td className="px-5 py-3.5 text-slate-200 font-medium">{item.${f.name}}</td>`;
  })
  .join('\n')}
                      <td className="px-5 py-3.5 text-right">
                        <div className="flex items-center justify-end gap-2">
                          <button
                            onClick={() => {
                              setEditingItem(item);
                              setFormData(item);
                              setIsModalOpen(true);
                            }}
                            className="p-1 text-slate-400 hover:text-slate-200 transition-colors"
                            title="Edit"
                          >
                            <Edit2 className="w-3.5 h-3.5" />
                          </button>
                          <button
                            onClick={() => handleDelete(item.id)}
                            className="p-1 text-rose-400 hover:text-rose-300 transition-colors"
                            title="Delete"
                          >
                            <Trash2 className="w-3.5 h-3.5" />
                          </button>
                        </div>
                      </td>
                    </tr>
                  ))
                )}
              </tbody>
            </table>
          </div>
        </div>

        {/* Modal Dialog */}
        {isModalOpen && (
          <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/70 backdrop-blur-sm">
            <div className="w-full max-w-lg bg-slate-900 border border-slate-800 rounded-xl p-6 shadow-2xl">
              <h2 className="text-lg font-semibold text-white mb-4">
                {editingItem ? 'Edit ${entityName}' : 'Add New ${entityName}'}
              </h2>

              <form onSubmit={handleCreateOrUpdate} className="space-y-4">
${fields
  .filter((f) => !f.isId)
  .map(
    (f) => `                <div>
                  <label className="block text-xs font-medium text-slate-400 mb-1">
                    ${f.label}
                  </label>
                  <input
                    type="${f.type === 'number' ? 'number' : 'text'}"
                    required={${Boolean(f.required)}}
                    value={(formData as any).${f.name} ?? ''}
                    onChange={(e) =>
                      setFormData({
                        ...formData,
                        ${f.name}: ${f.type === 'number' ? 'Number(e.target.value)' : 'e.target.value'},
                      })
                    }
                    className="w-full px-3 py-2 text-sm bg-slate-950 border border-slate-800 rounded-lg text-slate-100 focus:outline-none focus:ring-2 focus:ring-indigo-500"
                  />
                </div>`
  )
  .join('\n')}

                <div className="flex items-center justify-end gap-3 pt-4 border-t border-slate-800">
                  <button
                    type="button"
                    onClick={() => setIsModalOpen(false)}
                    className="px-4 py-2 text-xs font-medium text-slate-300 hover:text-white bg-slate-800 hover:bg-slate-700 rounded-lg transition-colors"
                  >
                    Cancel
                  </button>
                  <button
                    type="submit"
                    className="px-4 py-2 text-xs font-medium text-white bg-indigo-600 hover:bg-indigo-500 rounded-lg transition-colors"
                  >
                    {editingItem ? 'Save Changes' : 'Create Record'}
                  </button>
                </div>
              </form>
            </div>
          </div>
        )}
      </div>
    </div>
  );
}
`;
}
